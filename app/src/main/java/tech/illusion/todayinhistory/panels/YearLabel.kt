package tech.illusion.todayinhistory.panels

import kotlin.math.abs

/**
 * 把年份整数格式化成展示文本。
 *
 * ### 两套纪年约定各管一段，0 与 −1 故意合流
 *
 * 这里**混用了两套互斥的纪年约定**，是有意的，别当成不一致去「修正」：
 *
 * - **负数走历史纪年**：`-1046` → 「公元前 1046 年」，直接取绝对值。
 *   上游数据用的就是这套（`-1046` 指武王伐纣那年，不是天文纪年的 −1046）。
 * - **0 走天文纪年**：`0` → 「公元前 1 年」。历史纪年里根本没有 0 这个取值，
 *   所以 0 只能按天文纪年解释，而天文纪年的 0 就是公元前 1 年。
 *
 * 若两段都按天文纪年，`-1046` 应渲染成「公元前 1047 年」——那会和上游数据的
 * 含义对不上。所以负数段保持历史纪年，只有 0 这个上游不产生的取值借天文纪年定义。
 *
 * **代价**：`formatYear(0)` 与 `formatYear(-1)` 输出完全相同（都是「公元前 1 年」），
 * 两个不同的输入渲染成同一串文本。这是上面那个选择的必然结果，且无害——
 * 上游数据不产生 0（Task 1 的构建脚本产出里未见），只有解析器允许它通过。
 * 两条测试都钉住了，改这里会同时打红。
 *
 * ### 其它
 *
 * 取绝对值走 [Long]：`abs(Int.MIN_VALUE)` 在补码下会溢出回 `Int.MIN_VALUE` 自身，
 * 用 Int 取绝对值会渲染出「公元前 -2147483648 年」这种带负号的畸形文本。
 *
 * 这里刻意**不走 string 资源**：格式化是纯逻辑，不依赖 Android framework，
 * 因此能在 JVM 单测里直接验证（见 `YearLabelTest`）。类型标签那类需要本地化的
 * 文案才走 [labelOf] + `stringResource`。
 *
 * @param year 年份；负数为公元前，0 见上文。
 */
fun formatYear(year: Int): String =
    when {
        year > 0 -> "$year 年"
        year == 0 -> "公元前 1 年"
        else -> "公元前 ${abs(year.toLong())} 年"
    }
